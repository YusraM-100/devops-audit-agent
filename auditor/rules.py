def catalogue_text() -> str:
    lines = []
    for rule_id, category, severity, meaning, ok in RULES:
        lines.append(f"{rule_id} [{category}, default {severity}] {meaning}. NOT a violation if: {ok}.")
    return "\n".join(lines)


def normalize_category(value: str | None) -> str | None:
    if not value:
        return None
    key = str(value).strip().lower()
    if key in CATEGORIES:
        return key
    key = CATEGORY_ALIASES.get(key, key.replace(" ", "_").replace("-", "_"))
    return key if key in CATEGORIES else None
